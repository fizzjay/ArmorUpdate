"""Map unchanged worn triangles to compact ingredient UV groups.
Exact atlas matches take priority; authored component ownership disambiguates
reused UVs and supplies ownership for differing LOD topology. No vertex edits.
"""
from pathlib import Path
import sys,io,struct,collections,base64
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from tools.skin_metal import parse

def build():
 s=io.BytesIO((ROOT/'crafting/construction.bin').read_bytes());s.read(40)
 def r(f):return struct.unpack('<'+f,s.read(struct.calcsize('<'+f)))
 def text():return s.read(r('i')[0]).decode()
 plans={}
 for _ in range(r('i')[0]):
  name=text();text();parts=[]
  for j in range(r('i')[0]):
   r('Iii?');r('7fi');v=[r('8f') for _ in range(r('i')[0])];ts=[]
   for _ in range(r('i')[0]):
    ids=r(str(r('i')[0])+'i');ts += [tuple(v[i][6:8] for i in ids[k:k+3]) for k in range(0,len(ids),3)]
   parts.append(ts)
  plans[name]=parts
 _,meshes,pieces=parse((ROOT/'quest/ArmorRestored.armor.pack').read_bytes())
 def key(t):return tuple(sorted(tuple(round(x,5) for x in uv) for uv in t))
 result={}
 for p in pieces[8:16]:
  lookup=collections.defaultdict(set); vertices=collections.defaultdict(set)
  for i,ts in enumerate(plans[p['id']]):
   for t in ts:
    lookup[key(t)].add(i)
    for uv in t: vertices[tuple(round(x,5) for x in uv)].add(i)
  for part in p['parts']:
   m=meshes[part['mesh']];name=m['name'];groups=[]
   # Ownership for components with reused atlas islands/different LOD topology.
   # These correspond to authored primary/closure groups, NOT material names.
   fallback=0
   if name.startswith('cuirass_02'):fallback=1
   if name.startswith('rerebrace_'):fallback=2 if '_02_' in name else 1
   votes=collections.Counter()
   for sub in m['subs']:
    ids=[i[0] for i in sub]
    for k in range(0,len(ids),3):
     matches=lookup.get(key([m['uv'][i] for i in ids[k:k+3]]),set())
     if len(matches)==1:votes[next(iter(matches))]+=1
   if votes and not name.startswith(('cuirass_','rerebrace_')):fallback=votes.most_common(1)[0][0]
   for sub in m['subs']:
    ids=[i[0] for i in sub]
    for k in range(0,len(ids),3):
     matches=lookup.get(key([m['uv'][i] for i in ids[k:k+3]]),set())
     if len(matches)!=1:
      vertex_matches=[vertices.get(tuple(round(x,5) for x in m['uv'][i]),set()) for i in ids[k:k+3]]
      common=set.intersection(*vertex_matches)
      if len(common)==1: matches=common
     group=next(iter(matches)) if len(matches)==1 else fallback
     if 'glove_flair' in name:group=255
     groups.append(group)
   result[name]=groups
 return result

